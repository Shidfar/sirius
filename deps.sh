#!/usr/bin/env bash
# Builds the static libraries that go into the single `sirius` binary, from pinned, checksummed sources.
#
#   ./deps.sh              libraries for this machine's CPU           -> deps/x86_64/ or deps/aarch64/
#   ./deps.sh aarch64      cross-compile for a 64-bit Raspberry Pi    (needs gcc-aarch64-linux-gnu on an x86_64 PC)
#
# Needs: a C compiler, make, cmake, curl, unzip, tar with xz and bzip2.
# Sources are downloaded once into deps/src/ and checked against the SHA-256 sums below.
set -euo pipefail
cd "$(dirname "$0")"

ARCH="${1:-$(uname -m)}"
case "$ARCH" in
  x86_64|aarch64) ;;
  arm64) ARCH=aarch64 ;;
  *) echo "unsupported CPU: $ARCH (use x86_64 or aarch64)" >&2; exit 1 ;;
esac
HOST_ARCH="$(uname -m)"
if [ "$ARCH" = "$HOST_ARCH" ]; then
  TRIPLET=""; CROSS=""
else
  [ "$ARCH" = aarch64 ] && [ "$HOST_ARCH" = x86_64 ] || { echo "cannot build $ARCH libraries on $HOST_ARCH" >&2; exit 1; }
  TRIPLET=aarch64-linux-gnu; CROSS=aarch64-linux-gnu-
  command -v ${CROSS}gcc >/dev/null || { echo "install the cross compiler: sudo apt install gcc-aarch64-linux-gnu" >&2; exit 1; }
fi
export AR="${CROSS}ar" RANLIB="${CROSS}ranlib" STRIP="${CROSS}strip"
export CFLAGS="-O2 -fPIC"

TOP="$PWD"
SRC="$TOP/deps/src"
PREFIX="$TOP/deps/$ARCH"
WORK="$TOP/deps/build-$ARCH"
JOBS="$(nproc)"
mkdir -p "$SRC" "$PREFIX/lib" "$PREFIX/include" "$WORK"

HOSTARG=(); [ -n "$TRIPLET" ] && HOSTARG=(--host="$TRIPLET")

fetch() {  # fetch FILE URL SHA256
  local f="$SRC/$1"
  [ -f "$f" ] || { echo "== downloading $1"; curl -fL --retry 3 -o "$f.part" "$2" && mv "$f.part" "$f"; }
  echo "$3  $f" | sha256sum -c --status - || { echo "$1: checksum mismatch - delete $f and try again" >&2; exit 1; }
}
unpack() {  # unpack FILE -> directory name in $WORK
  rm -rf "$WORK/$2"; tar -C "$WORK" -xf "$SRC/$1"
}
stamp() { [ -f "$PREFIX/.built-$1" ]; }
done_() { touch "$PREFIX/.built-$1"; }

# Cross builds use Debian 12's C library headers and libraries, so the binary runs on Debian 12 (Raspberry Pi OS
# "bookworm") and anything newer. Building against a newer glibc makes it refuse to start on older systems.
if [ -n "$TRIPLET" ]; then
  DEB=https://deb.debian.org/debian/pool/main
  fetch libc6_2.36-9+deb12u14_arm64.deb     $DEB/g/glibc/libc6_2.36-9+deb12u14_arm64.deb     01f4330719fd4f65580e16ea5a0527f372fca750e8f588d26deaf09f2d3b1cf4
  fetch libc6-dev_2.36-9+deb12u14_arm64.deb $DEB/g/glibc/libc6-dev_2.36-9+deb12u14_arm64.deb 8bc395bf2ee9939f1a6ae395f974cffdcf541d98f99adfe89ce7e4bef36d159e
  fetch linux-libc-dev_6.1.176-1_arm64.deb  $DEB/l/linux/linux-libc-dev_6.1.176-1_arm64.deb  eeca5ec13bed7206f8171fab9a48e84119dcc20cc79557f104628447a524ad10
  SYSROOT="$TOP/deps/sysroot-$ARCH"
  if [ ! -f "$SYSROOT/.done" ]; then
    rm -rf "$SYSROOT"; mkdir -p "$SYSROOT"
    for d in libc6_2.36-9+deb12u14_arm64.deb libc6-dev_2.36-9+deb12u14_arm64.deb linux-libc-dev_6.1.176-1_arm64.deb; do
      dpkg-deb -x "$SRC/$d" "$SYSROOT"
    done
    touch "$SYSROOT/.done"
  fi
  CCWRAP="$TOP/deps/cc-$ARCH"
  { echo '#!/bin/sh'
    echo "# generated by deps.sh: Ubuntu's cross gcc with Debian 12's C library"
    echo "S='$SYSROOT'"
    echo "exec ${CROSS}gcc --sysroot=\"\$S\" -nostdinc -isystem '$(${CROSS}gcc -print-file-name=include)' \\"
    echo "    -isystem \"\$S/usr/include/$TRIPLET\" -isystem \"\$S/usr/include\" \\"
    echo "    -B\"\$S/usr/lib/$TRIPLET\" -L\"\$S/usr/lib/$TRIPLET\" -L\"\$S/lib/$TRIPLET\" \"\$@\""
  } >"$CCWRAP"
  chmod +x "$CCWRAP"
  export CC="$CCWRAP"
else
  export CC=gcc
fi

fetch libsodium-1.0.20.tar.gz https://github.com/jedisct1/libsodium/releases/download/1.0.20-RELEASE/libsodium-1.0.20.tar.gz ebb65ef6ca439333c2bb41a0c1990587288da07f6c7fd07cb3a18cc18d30ce19
fetch libogg-1.3.5.tar.gz     https://github.com/xiph/ogg/releases/download/v1.3.5/libogg-1.3.5.tar.gz                    0eb4b4b9420a0f51db142ba3f9c64b333f826532dc0f48c6410ae51f4799b664
fetch opus-1.5.2.tar.gz       https://github.com/xiph/opus/releases/download/v1.5.2/opus-1.5.2.tar.gz                      65c1d2f78b9f2fb20082c38cbe47c951ad5839345876e46941612ee87f9a7ce1
fetch mbedtls-3.6.2.tar.bz2   https://github.com/Mbed-TLS/mbedtls/releases/download/mbedtls-3.6.2/mbedtls-3.6.2.tar.bz2    8b54fb9bcf4d5a7078028e0520acddefb7900b3e66fec7f7175bb5b7d85ccdca
fetch curl-8.11.1.tar.xz      https://curl.se/download/curl-8.11.1.tar.xz                                                  c7ca7db48b0909743eaef34250da02c19bc61d4f1dcedd6603f109409536ab56
fetch alsa-lib-1.2.12.tar.bz2 https://www.alsa-project.org/files/pub/lib/alsa-lib-1.2.12.tar.bz2                           4868cd908627279da5a634f468701625be8cc251d84262c7e5b6a218391ad0d2
fetch lg-0.2.2.zip            http://abyz.me.uk/lg/lg.zip                                                                  bb31c6031b632911a4cbbd1d47ea326f1249b9f9efe1504eca83d1e0ef0394af

autotools() {  # autotools NAME DIR [configure args...]
  local name="$1" dir="$2"; shift 2
  stamp "$name" && return
  echo "== building $name ($ARCH)"
  ( cd "$WORK/$dir" && ./configure "${HOSTARG[@]}" --prefix="$PREFIX" --disable-shared --enable-static --with-pic "$@" >"$WORK/$name.log" 2>&1 \
      && make -j"$JOBS" >>"$WORK/$name.log" 2>&1 && make install >>"$WORK/$name.log" 2>&1 ) \
    || { echo "$name failed, see $WORK/$name.log" >&2; tail -20 "$WORK/$name.log" >&2; exit 1; }
  done_ "$name"
}

stamp sodium || unpack libsodium-1.0.20.tar.gz libsodium-1.0.20
autotools sodium libsodium-1.0.20

stamp ogg || unpack libogg-1.3.5.tar.gz libogg-1.3.5
autotools ogg libogg-1.3.5

stamp opus || unpack opus-1.5.2.tar.gz opus-1.5.2
autotools opus opus-1.5.2 --disable-doc --disable-extra-programs

if ! stamp mbedtls; then
  echo "== building mbedtls ($ARCH)"
  unpack mbedtls-3.6.2.tar.bz2 mbedtls-3.6.2
  CMAKE_ARGS=(-DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX="$PREFIX" -DCMAKE_C_COMPILER="$CC" -DCMAKE_AR="$(command -v "$AR")"
              -DENABLE_PROGRAMS=OFF -DENABLE_TESTING=OFF -DUSE_SHARED_MBEDTLS_LIBRARY=OFF -DUSE_STATIC_MBEDTLS_LIBRARY=ON
              -DCMAKE_POSITION_INDEPENDENT_CODE=ON)
  [ -n "$TRIPLET" ] && CMAKE_ARGS+=(-DCMAKE_SYSTEM_NAME=Linux -DCMAKE_SYSTEM_PROCESSOR="$ARCH")
  ( cmake -S "$WORK/mbedtls-3.6.2" -B "$WORK/mbedtls-3.6.2/build" "${CMAKE_ARGS[@]}" >"$WORK/mbedtls.log" 2>&1 \
      && cmake --build "$WORK/mbedtls-3.6.2/build" -j"$JOBS" >>"$WORK/mbedtls.log" 2>&1 \
      && cmake --install "$WORK/mbedtls-3.6.2/build" >>"$WORK/mbedtls.log" 2>&1 ) \
    || { echo "mbedtls failed, see $WORK/mbedtls.log" >&2; tail -20 "$WORK/mbedtls.log" >&2; exit 1; }
  done_ mbedtls
fi

# libcurl: HTTP(S) only, TLS through mbedtls, no optional compression / HTTP/2 / name-handling libraries.
stamp curl || unpack curl-8.11.1.tar.xz curl-8.11.1
autotools curl curl-8.11.1 --with-mbedtls="$PREFIX" --without-zlib --without-brotli --without-zstd \
  --without-nghttp2 --without-libidn2 --without-libpsl --without-libssh2 --without-librtmp --disable-ldap --disable-ldaps \
  --disable-rtsp --disable-dict --disable-telnet --disable-tftp --disable-pop3 --disable-imap --disable-smtp --disable-gopher \
  --disable-mqtt --disable-smb --disable-ftp --disable-file --disable-manual --disable-docs --disable-ntlm --disable-websockets \
  --disable-ares --disable-curldebug --disable-verbose --without-libgsasl --disable-progress-meter

# ALSA: capture only. It reads /usr/share/alsa/alsa.conf at run time (part of Raspberry Pi OS).
stamp alsa || unpack alsa-lib-1.2.12.tar.bz2 alsa-lib-1.2.12
autotools alsa alsa-lib-1.2.12 --disable-python --disable-mixer --disable-rawmidi --disable-seq --disable-ucm --disable-topology \
  --disable-hwdep --disable-aload --disable-old-symbols --disable-alisp --disable-resmgr --disable-debug --with-configdir=/usr/share/alsa

# lgpio (GPIO + SPI for the e-Paper driver): only the library part of the project
if ! stamp lgpio; then
  echo "== building lgpio ($ARCH)"
  rm -rf "$WORK/lg"; mkdir -p "$WORK/lg"; unzip -q "$SRC/lg-0.2.2.zip" -d "$WORK/lg"
  ( cd "$WORK/lg/lg" && for f in lgCtx lgDbg lgErr lgGpio lgHdl lgI2C lgNotify lgPthAlerts lgPthTx lgSerial lgSPI lgThread lgUtil; do
        $CC -O2 -Wall -pthread -fPIC -c "$f.c" -o "$f.o"; done \
      && $AR rcs "$PREFIX/lib/liblgpio.a" lg*.o && $RANLIB "$PREFIX/lib/liblgpio.a" && cp lgpio.h "$PREFIX/include/" ) \
    >"$WORK/lgpio.log" 2>&1 || { echo "lgpio failed, see $WORK/lgpio.log" >&2; tail -20 "$WORK/lgpio.log" >&2; exit 1; }
  done_ lgpio
fi

echo "done: $PREFIX"
ls "$PREFIX/lib"/*.a
